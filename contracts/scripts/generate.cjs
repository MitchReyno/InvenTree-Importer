const { mkdir, readFile, writeFile } = require('node:fs/promises')
const { resolve } = require('node:path')
const { compile } = require('json-schema-to-typescript')
// Pinned Node natively erases the runtime schema module's types; no tsx/tool loader.
const { schemas } = require('../src/index.ts')

async function main() {
  const response = (name) => ({
    description: name,
    content: { 'application/json': { schema: { $ref: `#/components/schemas/${name}` } } },
  })
  const post = (input, output, status = '200') => ({
    requestBody: {
      required: true,
      content: { 'application/json': { schema: { $ref: `#/components/schemas/${input}` } } },
    },
    responses: {
      [status]: response(output),
      400: response('ErrorDto'),
      403: response('ErrorDto'),
      409: response('ErrorDto'),
      412: response('ErrorDto'),
      422: response('ErrorDto'),
    },
  })
  const document = {
    openapi: '3.1.0',
    info: { title: 'Bench Intake foundation', version: 'bench-intake-app/1' },
    paths: {
      '/api/v1/health': { get: { responses: { 200: response('Health') } } },
      '/api/v1/bootstrap': {
        get: { responses: { 200: response('Bootstrap'), 403: response('ErrorDto') } },
      },
      '/api/v1/batches': {
        get: { responses: { 200: response('CaptureList') } },
        post: post('BatchCreate', 'CaptureSnapshot', '201'),
      },
      '/api/v1/batches/{id}': {
        parameters: [
          {
            name: 'id',
            in: 'path',
            required: true,
            schema: schemas.Id ?? require('../src/index.ts').Id,
          },
        ],
        get: { responses: { 200: response('CaptureSnapshot') } },
      },
      '/api/v1/batches/{id}/edits': {
        parameters: [
          { name: 'id', in: 'path', required: true, schema: require('../src/index.ts').Id },
        ],
        post: post('CaptureEdit', 'CaptureSnapshot'),
      },
      '/api/v1/batches/{id}/observations': {
        parameters: [
          { name: 'id', in: 'path', required: true, schema: require('../src/index.ts').Id },
        ],
        post: post('CaptureObserve', 'CaptureObservation', '201'),
      },
      '/api/v1/activity': { get: { responses: { 200: response('ManualActivity') } } },
      '/api/v1/batches/{id}/manual': { get: { responses: { 200: response('ManualWorkspace') } } },
      '/api/v1/batches/{id}/reviews': { post: post('ManualScope', 'ManualReviewResult') },
      '/api/v1/batches/{id}/preparations': { post: post('ManualScope', 'ManualPreparationResult') },
      '/api/v1/preparations/{id}/approvals': { post: post('Approval', 'ManualAccepted') },
      '/api/v1/runs/{id}': { get: { responses: { 200: response('ManualRun') } } },
      '/api/v1/runs/{id}/start': { post: post('ManualRunCommand', 'ManualAccepted') },
      '/api/v1/runs/{id}/cancel': { post: post('ManualRunCommand', 'ManualAccepted') },
      '/api/v1/runs/{id}/recover': { post: post('ManualRecoveryCommand', 'ManualAccepted') },
    },
    components: { schemas },
  }
  for (const [path, item] of Object.entries(document.paths)) {
    if (path.includes('{id}') && !item.parameters) {
      item.parameters = [
        { name: 'id', in: 'path', required: true, schema: require('../src/index.ts').Id },
      ]
    }
  }
  // Paths advertise the implemented manual and capture commands; future processing stays absent.
  const files = {
    'openapi.json': JSON.stringify(document, null, 2) + '\n',
    'api.d.ts': (
      await Promise.all(
        Object.entries(schemas).map(([name, schema]) =>
          compile(schema, name, { bannerComment: '', additionalProperties: false }),
        ),
      )
    ).join('\n'),
    'client.ts': `// Generated by contracts/scripts/generate.cjs; do not edit.
import type { Bootstrap, Health, BatchCreate, CaptureEdit, CaptureList, CaptureSnapshot, CaptureObserve, CaptureObservation, ManualWorkspace, ManualReviewResult, ManualPreparationResult, ManualRun, ManualAccepted, ManualActivity } from './api.d.ts'
import { validate } from '../src/index.ts'
import type { ManualScopeDto, ApprovalDto, ManualRunCommandDto, ManualRecoveryCommandDto } from '../src/index.ts'
export class IntakeRequestError extends Error {
  constructor(public readonly status: number, public readonly code: string) { super(code) }
}
export function captureClient(baseUrl: string, csrfToken: string, transport: typeof fetch = fetch) {
  async function request<T>(path: string, schema: Parameters<typeof validate>[0], body?: unknown, key?: string): Promise<T> {
    const response = await transport(new URL(path, baseUrl), {
      method: body === undefined ? 'GET' : 'POST', redirect: 'error', signal: AbortSignal.timeout(10000),
      headers: body === undefined ? {} : { 'content-type': 'application/json', 'x-intake-csrf': csrfToken, 'idempotency-key': key ?? crypto.randomUUID() },
      body: body === undefined ? undefined : JSON.stringify(body),
    })
    const value: unknown = await response.json()
    if (!response.ok) {
      validate('ErrorDto', value)
      throw new IntakeRequestError(response.status, (value as { code: string }).code)
    }
    validate(schema, value)
    return value as T
  }
  return {
    list: () => request<CaptureList>('/api/v1/batches', 'CaptureList'),
    read: (id: string) => request<CaptureSnapshot>('/api/v1/batches/' + encodeURIComponent(id), 'CaptureSnapshot'),
    create: (input: BatchCreate, key: string) => request<CaptureSnapshot>('/api/v1/batches', 'CaptureSnapshot', input, key),
    edit: (id: string, input: CaptureEdit, key: string) => request<CaptureSnapshot>('/api/v1/batches/' + encodeURIComponent(id) + '/edits', 'CaptureSnapshot', input, key),
    observe: (id: string, input: CaptureObserve, key: string) => request<CaptureObservation>('/api/v1/batches/' + encodeURIComponent(id) + '/observations', 'CaptureObservation', input, key),
  }
}
export function manualClient(baseUrl: string, csrfToken: string, transport: typeof fetch = fetch) {
  async function request<T>(
    path: string,
    schema: Parameters<typeof validate>[0],
    body?: unknown,
    key?: string,
  ): Promise<T> {
    const response = await transport(new URL(path, baseUrl), {
      method: body === undefined ? 'GET' : 'POST',
      redirect: 'error',
      signal: AbortSignal.timeout(45000),
      headers: body === undefined ? {} : {
        'content-type': 'application/json',
        'x-intake-csrf': csrfToken,
        'idempotency-key': key ?? crypto.randomUUID(),
      },
      body: body === undefined ? undefined : JSON.stringify(body),
    })
    const value: unknown = await response.json()
    if (!response.ok) {
      validate('ErrorDto', value)
      throw new IntakeRequestError(response.status, (value as { code: string }).code)
    }
    validate(schema, value)
    return value as T
  }
  function batchPath(id: string, action: string) {
    return '/api/v1/batches/' + encodeURIComponent(id) + '/' + action
  }
  function runPath(id: string, action?: string) {
    return '/api/v1/runs/' + encodeURIComponent(id) + (action ? '/' + action : '')
  }
  return {
    activity: () => request<ManualActivity>('/api/v1/activity', 'ManualActivity'),
    workspace: (id: string) =>
      request<ManualWorkspace>(batchPath(id, 'manual'), 'ManualWorkspace'),
    review: (id: string, input: ManualScopeDto, key: string) =>
      request<ManualReviewResult>(batchPath(id, 'reviews'), 'ManualReviewResult', input, key),
    prepare: (id: string, input: ManualScopeDto, key: string) =>
      request<ManualPreparationResult>(batchPath(id, 'preparations'), 'ManualPreparationResult', input, key),
    approve: (input: ApprovalDto, key: string) =>
      request<ManualAccepted>(
        '/api/v1/preparations/' + encodeURIComponent(input.preparation_id) + '/approvals',
        'ManualAccepted', input, key,
      ),
    run: (id: string) => request<ManualRun>(runPath(id), 'ManualRun'),
    start: (id: string, input: ManualRunCommandDto, key: string) =>
      request<ManualAccepted>(runPath(id, 'start'), 'ManualAccepted', input, key),
    cancel: (id: string, input: ManualRunCommandDto, key: string) =>
      request<ManualAccepted>(runPath(id, 'cancel'), 'ManualAccepted', input, key),
    recover: (id: string, input: ManualRecoveryCommandDto, key: string) =>
      request<ManualAccepted>(runPath(id, 'recover'), 'ManualAccepted', input, key),
  }
}
export function intakeClient(baseUrl: string, transport: typeof fetch = fetch) {
  return {
    async health(): Promise<Health> {
      const response = await transport(new URL('/api/v1/health', baseUrl), { redirect: 'error', signal: AbortSignal.timeout(5000) })
      if (!response.ok) throw new Error('intake_request_failed')
      const value: unknown = await response.json()
      validate('Health', value)
      return value as Health
    },
    async bootstrap(): Promise<Bootstrap> {
      const response = await transport(new URL('/api/v1/bootstrap', baseUrl), { redirect: 'error', signal: AbortSignal.timeout(5000) })
      if (!response.ok) throw new Error('intake_request_failed')
      const value: unknown = await response.json()
      validate('Bootstrap', value)
      return value as Bootstrap
    },
  }
}
`,
  }
  await mkdir(resolve(__dirname, '../generated'), { recursive: true })
  for (const [name, value] of Object.entries(files)) {
    const path = resolve(__dirname, '../generated', name)
    if (process.argv.includes('--check')) {
      if ((await readFile(path, 'utf8')) !== value) {
        throw new Error(`generated_contract_drift:${name}`)
      }
    } else {
      await writeFile(path, value)
    }
  }
}
main().catch((error) => {
  process.stderr.write(`${error.message}\n`)
  process.exitCode = 1
})
