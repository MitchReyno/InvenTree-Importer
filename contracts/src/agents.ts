import { SessionFailureSummary } from './session-failures.ts'
import { Type, type Static, type TProperties } from '@sinclair/typebox'
import { Id, IsoTime, Revision, CursorSequence } from './scalars.ts'
import {
  ProcessingState,
  ProcessingStageV2,
  ProcessingQuestionSpec,
  ProcessingProposalV2,
  StartFreshEligibility,
} from './processing.ts'

const object = <T extends TProperties>(properties: T) =>
  Type.Object(properties, { additionalProperties: false })

import { AgentSelection } from './agent-selection.ts'
import { SessionHistoryAttempt, SessionLatestStatus, SessionState } from './sessions.ts'
import type { AgentSelectionDto } from './agent-selection.ts'
export { AgentSelection, type AgentSelectionDto } from './agent-selection.ts'
/** How many sessions may run provider turns at once; waiting sessions hold no slot. */
export const SessionConcurrency = Type.Integer({ minimum: 1, maximum: 8 })
export type AgentProviderId = AgentSelectionDto['provider']
/** Suggested model IDs per provider, first one first; models stay free text. */
export const AGENT_MODEL_SUGGESTIONS: Record<AgentProviderId, readonly string[]> = {
  claude: ['sonnet', 'opus', 'haiku'],
  codex: ['gpt-6.1-sol', 'gpt-6.1-terra', 'gpt-6-astra', 'gpt-6-luna'],
}
/** The steps that can name their own provider and model; any other step uses the default. */
export const AGENT_SETTINGS_STAGES = ['examine', 'research', 'images', 'inventory'] as const
export type AgentSettingsStage = (typeof AGENT_SETTINGS_STAGES)[number]

// Bounded by the request body; the model ID pattern and its 128-character limit are checked on
// save, which answers invalid_agent_settings.
const modelText = Type.String()
const providerFields = {
  enabled: Type.Boolean(),
  authentication: AgentSelection.properties.authentication,
  /** May be empty while the provider is off. */
  default_model: modelText,
}
export const AgentProviderSettings = object(providerFields)
export const AgentStageSelection = object({
  provider: AgentSelection.properties.provider,
  model: modelText,
})
/** A step that is absent uses the default provider and its default model. */
export const AgentStageSelections = object({
  examine: Type.Optional(AgentStageSelection),
  research: Type.Optional(AgentStageSelection),
  images: Type.Optional(AgentStageSelection),
  inventory: Type.Optional(AgentStageSelection),
})
const agentSettingsFields = {
  providers: object({ claude: AgentProviderSettings, codex: AgentProviderSettings }),
  /** Null exactly when no provider is on. */
  default_provider: Type.Union([AgentSelection.properties.provider, Type.Null()]),
  stage_selections: AgentStageSelections,
  session_concurrency: SessionConcurrency,
  /** Copied into each new batch's instructions at creation. */
  new_batch_instructions: Type.String({ maxLength: 8192 }),
  /** Operator guidance sealed into each new session for Part descriptions. */
  part_description_style: Type.String({ maxLength: 500 }),
  /** Whether new batches start with Auto tags on. */
  auto_tags_default: Type.Boolean(),
  /** Web research for VM tool sessions, sealed into each new attempt. */
  web: object({ public_pages: Type.Boolean(), prefer_datasheets: Type.Boolean() }),
}
export const AgentSettings = object({ revision: CursorSequence, ...agentSettingsFields })
/** The whole settings object, saved under one revision. */
export const AgentSettingsUpdate = object({
  expected_revision: CursorSequence,
  /**
   * Generated by the client for each save and kept for its resends: a resend of a save that
   * already applied is answered from its receipt instead of applying again.
   */
  save_id: Id,
  ...agentSettingsFields,
})
/**
 * A resend's answer when its save had already applied: the revision it produced, not the
 * settings, which later saves may have changed. The client reads the settings after it.
 */
export const AgentSettingsSaveReplay = object({
  save_id: Id,
  revision: Revision,
  replayed: Type.Literal(true),
})
export const AgentSettingsSaveResult = Type.Union([AgentSettings, AgentSettingsSaveReplay])
/** The Agents page's filter chips; each applies its rule to both its rows and its count. */
export const AGENT_SESSION_FILTERS = [
  'needs_attention',
  'working',
  'waiting',
  'queued',
  'done_today',
  'all',
] as const
export type AgentSessionFilter = (typeof AGENT_SESSION_FILTERS)[number]
export const AgentSessionFilterSchema = Type.Union(
  AGENT_SESSION_FILTERS.map((filter) => Type.Literal(filter)),
)
/** An opaque position in the list's order, issued by the list itself. */
export const AgentSessionCursor = Type.String({
  minLength: 1,
  maxLength: 200,
  pattern: '^[A-Za-z0-9_-]+$',
})
/**
 * Which sessions to list. The browser's local day bounds date Done today; without them the list
 * neither counts nor filters by it.
 */
export const AgentSessionQuery = object({
  before: Type.Optional(AgentSessionCursor),
  filter: Type.Optional(AgentSessionFilterSchema),
  batch_id: Type.Optional(Id),
  day_start: Type.Optional(IsoTime),
  day_end: Type.Optional(IsoTime),
})
const time = Type.String({ maxLength: 40 })
const sessionCount = Type.Integer({ minimum: 0 })
/** An attempt before the session's current one, as its row folds it. */
export const AgentSessionEarlierAttempt = object({
  attempt_id: Id,
  number: Type.Integer({ minimum: 1 }),
  state: ProcessingState,
  session_state: Type.Union([SessionState, Type.Null()]),
  queued_at: time,
  /** Its latest transition into its current ended state; absent while live or unrecorded. */
  ended_at: Type.Optional(time),
  failure: Type.Optional(SessionFailureSummary),
})
/** The most earlier attempts one row carries; `earlier_attempt_count` counts them all. */
export const MAX_EARLIER_ATTEMPTS = 20
export const AgentSessionList = object({
  /** One row per session (job), its current attempt first; ordered by that attempt's queue time. */
  sessions: Type.Array(
    object({
      attempt_id: Id,
      batch_id: Id,
      job_id: Id,
      /** Null only for the batch-level Examine lead session. */
      subject_id: Type.Union([Id, Type.Null()]),
      stage: ProcessingStageV2,
      state: ProcessingState,
      /** Whether this attempt is the job's current one; a switch to another profile can end it. */
      latest_on_job: Type.Boolean(),
      attempt_number: Type.Integer({ minimum: 1 }),
      /** Null for the deterministic synthetic session profile. */
      selection: Type.Union([AgentSelection, Type.Null()]),
      settings_revision: Type.Union([Revision, Type.Null()]),
      queued_at: time,
      started_at: Type.Union([time, Type.Null()]),
      finished_at: Type.Union([time, Type.Null()]),
      /** When the attempt entered its current state, from its latest transition. */
      state_since: time,
      native_session_id: Type.Union([Type.String({ maxLength: 128 }), Type.Null()]),
      actual_model: Type.Union([Type.String({ maxLength: 128 }), Type.Null()]),
      progress: Type.Union([
        Type.Literal('queued'),
        Type.Literal('starting'),
        Type.Literal('responding'),
        Type.Literal('settled'),
      ]),
      occupies_lane: Type.Boolean(),
      /** Session profiles only. */
      session_state: Type.Union([SessionState, Type.Null()]),
      failure: Type.Optional(SessionFailureSummary),
      latest_status: Type.Union([SessionLatestStatus, Type.Null()]),
      /** Its batch's agents are paused: it starts no new work until resumed. */
      paused: Type.Optional(Type.Literal(true)),
      /** Its batch is archived. */
      archived: Type.Boolean(),
      runs_on: SessionHistoryAttempt.properties.runs_on,
      /** The web setting sealed in the attempt's input; null when its profile has no web access. */
      web: SessionHistoryAttempt.properties.web,
      start_fresh: StartFreshEligibility,
      /** Newest first, at most `MAX_EARLIER_ATTEMPTS`. */
      earlier_attempts: Type.Array(AgentSessionEarlierAttempt, { maxItems: MAX_EARLIER_ATTEMPTS }),
      earlier_attempt_count: sessionCount,
    }),
    { maxItems: 50 },
  ),
  filter: AgentSessionFilterSchema,
  /**
   * Sessions matching each chip in the list's scope; archived batches count only under All.
   * Done today is absent without the day bounds.
   */
  counts: object({
    needs_attention: sessionCount,
    working: sessionCount,
    waiting: sessionCount,
    queued: sessionCount,
    done_today: Type.Optional(sessionCount),
    all: sessionCount,
  }),
  /** Across every session in scope, whatever the filter and page. */
  totals: object({
    /** Attempts holding a slot, a stopped one still held until its worker is reaped included. */
    slots_in_use: sessionCount,
    queued: sessionCount,
    waiting: sessionCount,
  }),
  /** Every batch in scope with sessions, newest activity first, with how many match the filter. */
  batches: Type.Array(
    object({
      batch_id: Id,
      archived: Type.Boolean(),
      sessions: sessionCount,
      matching: sessionCount,
      /** The earliest retained start of any of its attempts; a resumed turn doesn't move it. */
      first_started_at: Type.Union([time, Type.Null()]),
    }),
    { maxItems: 1000 },
  ),
  /** More batches are in scope than the summary holds. */
  batches_truncated: Type.Optional(Type.Literal(true)),
  /** Every paused batch of the account, whether or not its sessions are on this page. */
  paused_batch_ids: Type.Optional(Type.Array(Id, { maxItems: 1000 })),
  /** More batches are paused than the list holds; each session row still says its own. */
  paused_truncated: Type.Optional(Type.Literal(true)),
  next_before: Type.Union([AgentSessionCursor, Type.Null()]),
  /** False when the configured profile runs no agent sessions, so an empty list means nothing. */
  sessions_supported: Type.Boolean(),
})
/** A saved instruction sent to the batch's sessions; finished ones are woken to apply it. */
export const InstructionDelivery = object({
  sessions: Type.Integer({ minimum: 0, maximum: 100000 }),
  woken: Type.Integer({ minimum: 0, maximum: 100000 }),
})
/** Pauses or resumes agent sessions; pausing cancels nothing. */
export const AgentPauseUpdate = object({ paused: Type.Boolean() })
export const AgentPause = object({ batch_id: Id, paused: Type.Boolean() })
export const AgentPauseAll = object({
  paused: Type.Boolean(),
  /** The batches the change reached. */
  batch_ids: Type.Array(Id, { maxItems: 1000 }),
})
/**
 * Why a provider's sign-in status could not be read. None of them means signed out: the session
 * worker didn't answer, the agent VM isn't connected, the provider's credential service is missing
 * or older than the status read, it is busy with a sign-in change, or it didn't answer in time.
 */
export const PROVIDER_STATUS_UNKNOWN_REASONS = [
  'not_configured',
  'worker_unavailable',
  'vm_unreachable',
  'service_unavailable',
  'guest_outdated',
  'busy',
  'timeout',
] as const
const providerStatusUnknown = {
  state: Type.Literal('unknown'),
  reason: Type.Union(PROVIDER_STATUS_UNKNOWN_REASONS.map((reason) => Type.Literal(reason))),
}
/** The provider's latest session, when it used the subscription and the provider refused sign-in. */
export const ProviderSignInFailure = object({
  attempt_id: Id,
  failure_id: Id,
  failed_at: Type.String({ maxLength: 40 }),
})
const lastSignInFailure = {
  last_sign_in_failure: Type.Union([ProviderSignInFailure, Type.Null()]),
}
export const ClaudeProviderStatus = Type.Union([
  object({
    state: Type.Literal('saved'),
    /** Null when the token was saved by a guest image that doesn't record the time. */
    saved_at: Type.Union([Type.String({ maxLength: 40 }), Type.Null()]),
    ...lastSignInFailure,
  }),
  object({ state: Type.Literal('not_saved'), ...lastSignInFailure }),
  object({ ...providerStatusUnknown, ...lastSignInFailure }),
])
export const CodexProviderStatus = Type.Union([
  object({
    state: Type.Union([
      Type.Literal('signed_in'),
      Type.Literal('signing_in'),
      Type.Literal('signed_out'),
    ]),
    ...lastSignInFailure,
  }),
  object({ ...providerStatusUnknown, ...lastSignInFailure }),
])
/**
 * Each VM provider's sign-in status, read without the management key. Display only: it carries no
 * token, account, key or credential revision, so nothing can be saved with it.
 */
export const ProviderStatus = object({
  claude: ClaudeProviderStatus,
  codex: CodexProviderStatus,
  /** When the guest was read; the server reuses a read for a few seconds. */
  read_at: Type.String({ maxLength: 40 }),
})
